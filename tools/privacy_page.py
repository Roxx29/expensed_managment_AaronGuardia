import markdown

root = pathlib.Path(__file__).resolve().parent.parent
body = markdown.markdown((root / 'PRIVACY.md').read_text(encoding='utf-8'))
page = f"""<!doctype html>
<html lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="referrer" content="no-referrer">
<title>Privacidad · Monchi</title>
<link rel="icon" href="/logo.png">
<style>
  /* Generated by tools/privacy_page.py from PRIVACY.md: edit that file, not this one. */
  :root {{ --bg: #131B2E; --card: #1C2540; --ink: #F3F5FA; --muted: #C5CCDA; --yellow: #FFC800; --line: rgba(255,255,255,.1); }}
  * {{ box-sizing: border-box; }}
  body {{ margin: 0; background: var(--bg); color: var(--ink); font: 16px/1.6 system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; padding: 16px; }}
  main {{ max-width: 760px; margin: 0 auto; background: var(--card); border: 1px solid var(--line); border-radius: 24px; padding: 28px 22px; }}
  h1 {{ font-size: 24px; margin-top: 0; }}
  h2 {{ font-size: 20px; margin-top: 32px; color: var(--yellow); }}
  p, li {{ color: var(--muted); }}
  strong {{ color: var(--ink); }}
  a {{ color: var(--yellow); }}
</style>
</head>
<body>
<main>
{body}
</main>
</body>
</html>
"""
out = root / 'admin_web' / 'privacidad' / 'index.html'
out.parent.mkdir(exist_ok=True)
out.write_text(page, encoding='utf-8')
print(out)
